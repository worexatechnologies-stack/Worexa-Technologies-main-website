export function getJobBySlug(slug) {
  if (!slug) return null;
  const normalizedSlug = slug.toLowerCase().trim();
  return (
    jobs.find((j) => j.slug === normalizedSlug) ||
    jobs.find((j) => j.slug.replace(/-/g, "") === normalizedSlug.replace(/-/g, "")) ||
    null
  );
}
